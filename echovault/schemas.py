"""Pydantic data schemas and typed contracts for EchoVault AI."""

from enum import Enum
from typing import List, Optional, Dict, Any
from datetime import datetime
from pydantic import BaseModel, Field


class ProcessingStatus(str, Enum):
    PENDING = "pending"
    PROCESSING = "processing"
    COMPLETED = "completed"
    FAILED = "failed"
    AI_DEGRADED = "ai_degraded"  # When AI model was unavailable, but data safely archived


class SourceType(str, Enum):
    MANUAL_TEXT = "manual_text"
    AUDIO_RECORDING = "audio_recording"
    IMPORT = "import"


class EntityType(str, Enum):
    PERSON = "person"
    PLACE = "place"
    DATE = "date"
    EVENT = "event"
    THEME = "theme"
    TOPIC = "topic"
    QUOTE = "quote"


class AuditAction(str, Enum):
    INTAKE_VALIDATED = "intake_validated"
    TRANSCRIPTION_COMPLETED = "transcription_completed"
    INTELLIGENCE_EXTRACTED = "intelligence_extracted"
    ARCHIVED = "archived"
    SEARCH_RETRIEVED = "search_retrieved"
    QUESTION_ANSWERED = "question_answered"
    MEMORY_EDITED = "memory_edited"
    MEMORY_DELETED = "memory_deleted"
    ARCHIVE_EXPORTED = "archive_exported"
    ARCHIVE_RESTORED = "archive_restored"


# ==========================================
# Intelligence Output Schemas (Gemma Contract)
# ==========================================

class ExtractedPerson(BaseModel):
    name: str = Field(description="Name of the person mentioned")
    relationship: Optional[str] = Field(default=None, description="Relationship to narrator (e.g., grandfather, mother), ONLY if explicitly stated")
    context: Optional[str] = Field(default=None, description="Brief mention context in source")


class ExtractedPlace(BaseModel):
    name: str = Field(description="Name of place, town, building, or region")
    location_type: Optional[str] = Field(default=None, description="Type (city, house, country, workplace)")
    context: Optional[str] = Field(default=None, description="Brief context")


class ExtractedDate(BaseModel):
    raw_date: str = Field(description="Date or time period as spoken in the memory (e.g. 'Summer of 1968', 'after the war')")
    iso_year: Optional[int] = Field(default=None, description="Estimated 4-digit calendar year if unambiguous")
    is_approximate: bool = Field(default=False, description="True if marked approximate (circa, around, roughly)")


class ExtractedQuote(BaseModel):
    quote_text: str = Field(description="Verbatim or near-verbatim quote from the narrative")
    speaker: Optional[str] = Field(default=None, description="Speaker attribution if explicitly identified")


class MemoryIntelligence(BaseModel):
    """Structured memory intelligence generated by Gemma or fallback heuristic."""
    title: str = Field(description="A respectful, evocative short title summarizing the core story")
    summary: str = Field(description="A concise 2-3 sentence factual summary preserving original tone")
    people: List[ExtractedPerson] = Field(default_factory=list, description="People explicitly mentioned")
    places: List[ExtractedPlace] = Field(default_factory=list, description="Places explicitly mentioned")
    dates: List[ExtractedDate] = Field(default_factory=list, description="Temporal references")
    quotes: List[ExtractedQuote] = Field(default_factory=list, description="Direct notable quotations")
    themes: List[str] = Field(default_factory=list, description="Key family themes (e.g., migration, military, craftsmanship)")
    topics: List[str] = Field(default_factory=list, description="Specific topics discussed")
    explicit_facts: List[str] = Field(default_factory=list, description="Key facts stated unequivocally")
    uncertainty_notes: List[str] = Field(default_factory=list, description="Items that narrator stated as uncertain or hazy")


# ==========================================
# Core Memory Entity Schemas
# ==========================================

class MemorySource(BaseModel):
    id: str
    memory_id: str
    source_type: SourceType
    original_filename: Optional[str] = None
    file_path: Optional[str] = None
    mime_type: Optional[str] = None
    file_size_bytes: int = 0
    duration_seconds: Optional[float] = None
    content_sha256: str
    created_at: datetime = Field(default_factory=datetime.utcnow)


class MemoryRecord(BaseModel):
    id: str
    title: str
    content: str
    summary: Optional[str] = None
    narrator: Optional[str] = "Family Member"
    event_date_raw: Optional[str] = None
    event_date_iso: Optional[str] = None
    uncertainty_notes: Optional[str] = None
    processing_status: ProcessingStatus = ProcessingStatus.PENDING
    content_hash: str
    source_type: SourceType = SourceType.MANUAL_TEXT
    created_at: datetime = Field(default_factory=datetime.utcnow)
    updated_at: datetime = Field(default_factory=datetime.utcnow)
    
    # Nested hydrated entities
    people: List[ExtractedPerson] = Field(default_factory=list)
    places: List[ExtractedPlace] = Field(default_factory=list)
    themes: List[str] = Field(default_factory=list)
    quotes: List[ExtractedQuote] = Field(default_factory=list)


# ==========================================
# Retrieval & Question Answering Schemas
# ==========================================

class RetrievedPassage(BaseModel):
    memory_id: str
    title: str
    passage: str
    narrator: Optional[str] = None
    event_date: Optional[str] = None
    relevance_score: float = 0.0


class GroundedAnswer(BaseModel):
    question: str
    answer: str
    citations: List[RetrievedPassage] = Field(default_factory=list)
    supporting_memory_titles: List[str] = Field(default_factory=list)
    is_abstention: bool = False
    abstention_reason: Optional[str] = None
    uncertainty_disclosure: Optional[str] = None


# ==========================================
# Orchestration & Audit Schemas
# ==========================================

class ExecutionStepTrace(BaseModel):
    agent_name: str
    stage: str
    status: str
    duration_ms: float
    message: str
    timestamp: datetime = Field(default_factory=datetime.utcnow)


class OrchestratorMemoryState(BaseModel):
    memory_id: str
    source_type: SourceType
    raw_content: str
    narrator: Optional[str] = "Family Member"
    raw_audio_path: Optional[str] = None
    transcript_text: Optional[str] = None
    intelligence: Optional[MemoryIntelligence] = None
    archived_record: Optional[MemoryRecord] = None
    processing_status: ProcessingStatus = ProcessingStatus.PENDING
    errors: List[str] = Field(default_factory=list)
    traces: List[ExecutionStepTrace] = Field(default_factory=list)


class AuditEvent(BaseModel):
    id: Optional[str] = None
    memory_id: Optional[str] = None
    action: AuditAction
    agent_name: str
    details: Dict[str, Any] = Field(default_factory=dict)
    timestamp: datetime = Field(default_factory=datetime.utcnow)
